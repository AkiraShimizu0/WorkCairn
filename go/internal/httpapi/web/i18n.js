let storageWarning = false;
let activeLocale = DEFAULT_LOCALE;

function fatalTranslationError() {
  document.documentElement.lang = "ja";
  document.body.replaceChildren(Object.assign(document.createElement("main"), {
    className: "i18n-fatal",
    textContent: "表示言語の設定を読み込めませんでした。 / The display-language configuration could not be loaded.",
  }));
  document.body.removeAttribute("data-i18n-pending");
  throw new Error("I18N_CONTRACT_INVALID");
}

function placeholderNames(value) {
  return [...new Set([...value.matchAll(PLACEHOLDER_PATTERN)].map((match) => match[1]))].sort();
}

function validateCatalogs() {
  const jaKeys = Object.keys(CATALOGS.ja).sort();
  const enKeys = Object.keys(CATALOGS.en).sort();
  if (JSON.stringify(jaKeys) !== JSON.stringify(enKeys)) return false;
  return jaKeys.every((key) => typeof CATALOGS.ja[key] === "string" && typeof CATALOGS.en[key] === "string" &&
    JSON.stringify(placeholderNames(CATALOGS.ja[key])) === JSON.stringify(placeholderNames(CATALOGS.en[key])));
}

if (!validateCatalogs()) fatalTranslationError();
try {
  const stored = localStorage.getItem(STORAGE_LOCALE);
  if (stored === "ja" || stored === "en") activeLocale = stored;
  else if (stored !== null) localStorage.removeItem(STORAGE_LOCALE);
} catch {
  storageWarning = true;
  activeLocale = DEFAULT_LOCALE;
}
document.documentElement.lang = activeLocale;

export function locale() { return activeLocale; }
export function localeTag() { return LOCALE_TAGS[activeLocale]; }
export function localeStorageWarning() { return storageWarning; }

export function t(key, parameters = {}) {
  const value = CATALOGS[activeLocale]?.[key];
  if (typeof value !== "string") return fatalTranslationError();
  const expected = placeholderNames(value);
  const actual = Object.keys(parameters).sort();
  if (JSON.stringify(expected) !== JSON.stringify(actual) || actual.some((name) => parameters[name] === null || parameters[name] === undefined || typeof parameters[name] === "object")) {
    return fatalTranslationError();
  }
  return value.replace(PLACEHOLDER_PATTERN, (_, name) => String(parameters[name]));
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
  for (const attribute of ["aria-label", "title", "placeholder"]) {
    const marker = "data-i18n-" + attribute;
    root.querySelectorAll("[" + marker + "]").forEach((element) => element.setAttribute(attribute, t(element.getAttribute(marker))));
  }
  document.body.removeAttribute("data-i18n-pending");
}

export function persistLocale(nextLocale) {
  if (nextLocale !== "ja" && nextLocale !== "en") return false;
  try {
    localStorage.setItem(STORAGE_LOCALE, nextLocale);
    return localStorage.getItem(STORAGE_LOCALE) === nextLocale;
  } catch {
    return false;
  }
}
